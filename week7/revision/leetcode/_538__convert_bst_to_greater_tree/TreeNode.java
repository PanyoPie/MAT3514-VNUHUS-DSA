package vn.io.tunaa.dsa.week7.revision.leetcode._538__convert_bst_to_greater_tree;

 public class TreeNode {
     int val;
     TreeNode left;
     TreeNode right;

     TreeNode() {

     }

     TreeNode(int val) {
         this.val = val;
     }

     TreeNode(int val, TreeNode left, TreeNode right) {
         this.val = val;
         this.left = left;
         this.right = right;
     }
 }